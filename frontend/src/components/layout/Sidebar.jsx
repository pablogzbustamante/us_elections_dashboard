function ExpandableNav({ icon, label, children, defaultOpen = false }) {
  const [open, setOpen] = useState(defaultOpen);
  return (
    <>
      <button className="nav-item" onClick={() => setOpen((o) => !o)}>
        {icon}
        <span style={{ flex: 1 }}>{label}</span>
        <svg
          className={`nav-chevron${open ? " open" : ""}`}
          viewBox="0 0 24 24"
          fill="none"
          stroke="currentColor"
          strokeWidth="2.5"
          strokeLinecap="round"
          strokeLinejoin="round"
        >
          <polyline points="6 9 12 15 18 9" />
        </svg>
      </button>
      {open && <div className="nav-sub">{children}</div>}
    </>
  );
}

